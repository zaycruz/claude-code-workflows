#!/usr/bin/env node
// Generates the workflow inventory from each workflow's meta. Usage:
//   node lib/gen-inventory.mjs [--out INVENTORY.md] | --check INVENTORY.md
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')

// Slice the bracketed literal starting at `start`, matching nesting outside
// quotes, template strings and comments. Reused for ${...} inside templates.
function litAt(src, start, open = '{', close = '}') {
  let depth = 0, i = start
  while (i < src.length) {
    const c = src[i]
    if (c === open || (open === '{' && c === '[')) depth++
    else if (c === close || (close === '}' && c === ']')) { if (--depth === 0) return src.slice(start, i + 1) }
    else if (c === '/' && (src[i + 1] === '/' || src[i + 1] === '*')) {
      const block = src[i + 1] === '*'
      i += 2
      while (i < src.length && !(block ? src[i] === '*' && src[i + 1] === '/' : src[i] === '\n')) i++
      if (block) i++
    } else if (c === '`' || c === "'" || c === '"') {
      const q = c
      i++
      while (i < src.length) {
        if (src[i] === '\\') i++
        else if (src[i] === q) break
        else if (q === '`' && src[i] === '$' && src[i + 1] === '{') {
          const inner = litAt(src, i + 1)
          if (inner) { i += inner.length - 1; break }
        }
        i++
      }
    }
    i++
  }
  return null
}

const asStrings = (lit) => {
  try {
    const v = new Function('return (' + lit + ')')()
    return Array.isArray(v) && v.length && v.every((x) => typeof x === 'string') ? v : null
  } catch { return null }
}

// Allowed-args literal: a literal `const ALLOWED = [...]`.
function allowedArgs(src) {
  for (const line of src.split('\n')) {
    const at = line.search(/\bALLOWED\s*=\s*\[/)
    if (at < 0) continue
    const v = asStrings(litAt(line, line.indexOf('[', at + 'ALLOWED'.length), '[', ']'))
    if (v) return v
  }
  return null
}

function loadWorkflows() {
  const out = []
  for (const f of fs.readdirSync(ROOT).sort()) {
    if (!f.endsWith('.js')) continue
    const src = fs.readFileSync(path.join(ROOT, f), 'utf8')
    const m = src.match(/export\s+const\s+meta\s*=\s*\{/)
    if (!m) continue
    out.push({
      meta: new Function('return (' + litAt(src, src.indexOf('{', m.index)) + ')')(),
      args: allowedArgs(src),
    })
  }
  return out
}

const esc = (s) => String(s ?? '').replace(/\\/g, '\\\\').replace(/\|/g, '\\|')
const flat = (s) => String(s ?? '').replace(/\s+/g, ' ').trim()
// First sentence, but not one ended by "e.g." or "i.e.".
const firstSentence = (s) => flat(String(s ?? '').match(/^(.*?(?<!\be\.g|\bi\.e)\.)(\s|$)/s)?.[1] ?? s)

function generate() {
  const wfs = loadWorkflows()
  const L = ['## Workflow inventory (generated)', '']
  L.push("Generated by `lib/gen-inventory.mjs` from each workflow's `meta`. Do not edit by hand;")
  L.push('re-run `node lib/gen-inventory.mjs --out INVENTORY.md` after changing any workflow.', '')
  L.push('| Workflow | What it does | Args accepted |', '| --- | --- | --- |')
  for (const w of wfs)
    L.push(`| \`${w.meta.name}\` | ${esc(firstSentence(w.meta.description))} | ${w.args ? w.args.map((a) => '`' + a + '`').join(', ') : 'see whenToUse'} |`)
  for (const w of wfs) {
    L.push('', `### ${w.meta.name}`, '', flat(w.meta.whenToUse), '')
    L.push(...(w.meta.phases || []).map((p, i) => `${i + 1}. **${p.title}** — ${p.detail}`))
  }
  return L.join('\n') + '\n'
}

const argv = process.argv.slice(2)
const at = (flag) => argv[argv.indexOf(flag) + 1]
if (argv.includes('--check')) {
  const p = at('--check') && !at('--check').startsWith('--') ? at('--check') : 'INVENTORY.md'
  const want = generate()
  if (!fs.existsSync(p) || fs.readFileSync(p, 'utf8') !== want) {
    console.error(`inventory is out of date: run node lib/gen-inventory.mjs --out ${p}`)
    process.exit(1)
  }
  console.log('inventory is up to date')
} else if (at('--out')) {
  fs.writeFileSync(at('--out'), generate())
} else {
  process.stdout.write(generate())
}
